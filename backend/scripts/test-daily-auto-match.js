require('dotenv').config();
const mongoose = require('mongoose');
const indiaTime = require('../utils/indiaTime');
const Game = require('../models/Game');
const GameMode = require('../models/GameMode');
const Tournament = require('../models/Tournament');
const DailyAutoMatch = require('../models/DailyAutoMatch');
const service = require('../services/dailyAutoMatchService');

const MONGODB_URI = process.env.MONGODB_URI || 'mongodb://127.0.0.1:27017/sk-win';
const TEST_NAME = '[TEST] Daily Auto Match';

function assert(cond, msg) {
  if (!cond) throw new Error(msg);
}

async function cleanup() {
  const masters = await DailyAutoMatch.find({ name: { $regex: /^\[TEST\]/ } });
  const ids = masters.map((m) => m._id);
  if (ids.length) {
    await Tournament.deleteMany({ autoMatchId: { $in: ids }, isAutoGenerated: true, name: { $regex: /^\[TEST\]/ } });
    await DailyAutoMatch.deleteMany({ _id: { $in: ids } });
  }
}

async function main() {
  console.log('indiaTime today:', indiaTime.getDateString());
  console.log('normalize 10:00 AM:', indiaTime.normalizeTime('10:00 AM'));
  assert(indiaTime.normalizeTime('10:00 AM') === '10:00', 'AM parse failed');
  assert(indiaTime.normalizeTime('2:00 PM') === '14:00', 'PM parse failed');
  const start = indiaTime.buildStartDate('2026-08-17', '10:00');
  assert(start.toISOString() === '2026-08-17T04:30:00.000Z', `IST conversion failed: ${start.toISOString()}`);
  assert(indiaTime.addDays('2026-08-17', 1) === '2026-08-18', 'addDays failed');

  await mongoose.connect(MONGODB_URI);
  await Tournament.syncIndexes();
  await DailyAutoMatch.syncIndexes();

  const game = await Game.findOne();
  const gameMode = game ? await GameMode.findOne({ game: game._id }) : null;
  if (!game || !gameMode) {
    console.log('SKIPPED DB flow: need at least one game + mode');
    await mongoose.disconnect();
    return;
  }

  await cleanup();

  const master = await service.createAutoMatch(
    {
      name: TEST_NAME,
      game: game._id,
      gameMode: gameMode._id,
      category: 'battle_royale',
      mode: 'solo',
      startTime: '10:00',
      entryFee: 20,
      prizePool: 500,
      isActive: true,
    },
    null
  );
  assert(master.displayId, 'displayId missing');
  assert(master.entryFee === 20, 'master entry fee');

  const first = await service.generateToday(master._id, { allowInactive: true });
  assert(first.created, 'first generate should create');
  assert(first.tournament.entryFee === 20, 'generated entry fee should copy master');
  assert(first.tournament.isAutoGenerated === true, 'isAutoGenerated');
  assert(String(first.tournament.autoMatchId) === String(master._id), 'autoMatchId');

  const second = await service.generateToday(master._id, { allowInactive: true });
  assert(second.alreadyExists, 'second generate must not duplicate');
  assert(String(second.tournament._id) === String(first.tournament._id), 'same tournament id');

  await Tournament.findByIdAndUpdate(first.tournament._id, { entryFee: 30 });
  const todayDoc = await Tournament.findById(first.tournament._id);
  const masterAfter = await DailyAutoMatch.findById(master._id);
  assert(todayDoc.entryFee === 30, 'today override');
  assert(masterAfter.entryFee === 20, 'master must stay 20');

  await service.updateAutoMatch(master._id, { prizePool: 700, entryFee: 20 });
  const masterUpdated = await DailyAutoMatch.findById(master._id);
  assert(masterUpdated.prizePool === 700, 'master prize updated');
  const todayUnchanged = await Tournament.findById(first.tournament._id);
  assert(todayUnchanged.prizePool === 500, 'today prize must stay 500');
  assert(todayUnchanged.entryFee === 30, 'today fee override must stay 30');

  const tomorrow = indiaTime.addDays(indiaTime.getDateString(), 1);
  const next = await service.generateForDate(master._id, tomorrow, { allowInactive: false });
  assert(next.created, 'tomorrow should generate');
  assert(next.tournament.prizePool === 700, 'tomorrow uses new master prize');
  assert(next.tournament.entryFee === 20, 'tomorrow uses master fee, not today override');

  await service.setActive(master._id, false);
  const dayAfter = indiaTime.addDays(tomorrow, 1);
  const skipped = await service.generateForDate(master._id, dayAfter);
  assert(skipped.skipped === true && skipped.reason === 'inactive', 'inactive must skip cron generation');

  await service.setActive(master._id, true);
  const resumed = await service.generateForDate(master._id, dayAfter);
  assert(resumed.created, 'reactivated generation should work');

  const listed = await service.listGeneratedTournaments(master._id);
  assert(listed.tournaments.length === 3, `expected 3 generated, got ${listed.tournaments.length}`);

  await cleanup();
  console.log('ALL DAILY AUTO MATCH CHECKS PASSED');
  await mongoose.disconnect();
}

main().catch(async (err) => {
  console.error('TEST FAILED:', err);
  try {
    await cleanup();
  } catch (e) {
    console.error('cleanup failed', e.message);
  }
  try {
    await mongoose.disconnect();
  } catch (_) {
    /* ignore */
  }
  process.exit(1);
});
