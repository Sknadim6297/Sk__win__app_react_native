const mongoose = require('mongoose');

const tournamentSchema = new mongoose.Schema({
  name: {
    type: String,
    required: true,
  },
  description: String,
  bannerImage: {
    type: String,
    default: '',
  },
  bannerTitle: {
    type: String,
    default: '',
    trim: true,
  },
  matchNumber: {
    type: Number,
    unique: true,
    sparse: true,
  },
  game: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Game',
    required: true,
  },
  gameMode: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'GameMode',
    required: true,
  },
  /** Admin-managed Match Type (Battle Royale / Clash Squad / Lone Wolf…). */
  matchType: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'MatchType',
  },
  /**
   * How players participate: solo | duo | squad.
   * Canonical field; `mode` is kept in sync for older code paths.
   * Never expose a UI label named "Format" — use "Player Format" / Solo|Duo|Squad.
   */
  playerFormat: {
    type: String,
    enum: ['solo', 'duo', 'squad'],
    default: 'solo',
  },
  /**
   * Joining units: individual seats (Solo) or team slots (Duo/Squad).
   * Named joiningSlots so it does not collide with the slot-booking array `slots`.
   * Public APIs expose this as `slots`.
   */
  joiningSlots: {
    type: Number,
    default: 48,
    min: 1,
  },
  mode: {
    type: String,
    enum: ['solo', 'duo', 'squad'],
    default: 'solo',
  },
  category: {
    type: String,
    enum: ['battle_royale', 'custom', 'custom_match'],
    default: 'battle_royale',
  },
  /** Primary lifecycle: draft → upcoming → ongoing → completed */
  lifecycleStatus: {
    type: String,
    enum: ['draft', 'upcoming', 'ongoing', 'completed', 'result_published', 'cancelled'],
    default: 'draft',
  },
  maxTeams: {
    type: Number,
    default: 2,
  },
  rewardType: {
    type: String,
    enum: ['per_kill', 'survival', 'hybrid'],
    default: 'per_kill',
  },
  resultsPublished: {
    type: Boolean,
    default: false,
  },
  resultsPublishedAt: {
    type: Date,
  },
  /** When true, PENDING winner payouts auto-credit on publish (TEST wallet). */
  autoPaymentEnabled: {
    type: Boolean,
    default: true,
  },
  map: {
    type: String,
    default: 'Bermuda',
  },
  rules: [{
    type: String,
  }],
  /** Free-text note shown on the published Match Result screen (e.g. proof submission instructions). */
  resultNote: {
    type: String,
    default: '',
    trim: true,
  },
  entryFee: {
    type: Number,
    required: true,
    // Always priced per player. Team modes charge entryFee × playersPerTeam at join.
  },
  prizePool: {
    type: Number,
    default: 0,
  },
  perKill: {
    type: Number,
    default: 0,
  },
  maxParticipants: {
    type: Number,
    required: true,
  },
  currentParticipants: {
    type: Number,
    default: 0,
  },
  registeredPlayers: [{
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
  }],
  status: {
    type: String,
    enum: [
      'draft', 'upcoming', 'ongoing', 'completed', 'result_published', 'cancelled',
      'incoming', 'live', 'locked',
    ],
    default: 'draft',
  },
  statusOverride: {
    type: Boolean,
    default: false,
  },
  locked: {
    type: Boolean,
    default: false,
  },
  lockedAt: {
    type: Date,
  },
  startDate: {
    type: Date,
    required: true,
  },
  endDate: Date,
  minimumBalance: {
    type: Number,
    default: 0,
  },
  roomId: String, // Game room ID
  roomPassword: String, // Game room password (encrypted)
  showRoomCredentials: {
    type: Boolean,
    default: false,
  },
  roomCredentialsSharedAt: {
    type: Date,
  },
  createdBy: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
  },
  prizes: {
    first: Number,
    second: Number,
    third: Number,
  },
  winners: [{
    userId: mongoose.Schema.Types.ObjectId,
    position: Number,
    reward: Number,
  }],
  // Slot booking system (50 fixed slots)
  slots: [{
    slotNumber: {
      type: Number,
      min: 1,
      max: 50,
    },
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      default: null,
    },
    gamingUsername: String,
    gamingUID: String,
    bookedAt: Date,
    isBooked: {
      type: Boolean,
      default: false,
    },
  }],
  createdAt: {
    type: Date,
    default: Date.now,
  },
  updatedAt: {
    type: Date,
    default: Date.now,
  },
  /** Set only on tournaments generated from a Daily Auto Match master. */
  isAutoGenerated: {
    type: Boolean,
    default: false,
  },
  autoMatchId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'DailyAutoMatch',
    default: undefined,
  },
  /** Calendar date in Asia/Kolkata as YYYY-MM-DD. Independent snapshot of that day's match. */
  generatedDate: {
    type: String,
    default: undefined,
  },
});

tournamentSchema.index({ lifecycleStatus: 1, startDate: -1 });
tournamentSchema.index({ status: 1, startDate: -1 });
tournamentSchema.index({ gameMode: 1, lifecycleStatus: 1 });
tournamentSchema.index({ category: 1, mode: 1 });
tournamentSchema.index({ name: 1 });
tournamentSchema.index({ createdAt: -1 });
tournamentSchema.index({ autoMatchId: 1, generatedDate: -1 });
tournamentSchema.index(
  { autoMatchId: 1, generatedDate: 1 },
  {
    unique: true,
    name: 'uniq_autoMatch_per_day',
    partialFilterExpression: {
      isAutoGenerated: true,
      autoMatchId: { $exists: true, $type: 'objectId' },
      generatedDate: { $exists: true, $type: 'string' },
    },
  }
);

module.exports = mongoose.model('Tournament', tournamentSchema);
