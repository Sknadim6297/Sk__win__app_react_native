router.post('/admin/:id/publish-results', authMiddleware, async (req, res) => {
  try {
    if (!(await requireAdmin(req, res))) return;

    const tournament = await Tournament.findById(req.params.id);
    if (!tournament) return res.status(404).json({ error: 'Tournament not found' });

    const status = lifecycle.getEffectiveStatus(tournament);
    if (status !== 'completed') {
      return res.status(400).json({ error: 'Tournament must be completed before publishing results' });
    }
    if (lifecycle.areResultsPublished(tournament)) {
      return res.status(400).json({
        error: 'Results already published — wallet payouts will not run again',
        alreadyPublished: true,
      });
    }

    const isTeamBr =
      lifecycle.isBattleRoyale(tournament) && lifecycle.usesTeamRegistration(tournament);

    if (lifecycle.isBattleRoyale(tournament)) {
      if (isTeamBr) {
        const teamCount = await Team.countDocuments({
          tournamentId: tournament._id,
          status: 'registered',
        });
        const resultCount = await BattleRoyaleTeamResult.countDocuments({
          tournamentId: tournament._id,
        });
        if (teamCount > 0 && resultCount < teamCount) {
          return res.status(400).json({
            error: 'Save placement and kills for every registered team first',
          });
        }
      } else {
        const joinedCount = await lifecycle.getJoinedCount(tournament._id, tournament);
        const resultCount = await BattleRoyaleResult.countDocuments({
          tournamentId: tournament._id,
        });
        if (joinedCount > 0 && resultCount < joinedCount) {
          return res.status(400).json({ error: 'Save results for every joined player first' });
        }
      }
    } else {
      const custom = await CustomMatchResult.findOne({ tournamentId: tournament._id });
      if (!custom) {
        return res.status(400).json({ error: 'Save Clash Squad results first' });
      }
    }

    const marked = lifecycle.markResultsPublished(tournament);
    if (!marked.ok) return res.status(400).json({ error: marked.error });
    await tournament.save();

    // Create WinnerPayout records + optional auto-credit (TEST wallet)
    let payoutSummary = { credited: 0 };
    try {
      if (lifecycle.isBattleRoyale(tournament)) {
        if (isTeamBr) {
          const teamRows = await BattleRoyaleTeamResult.find({
            tournamentId: tournament._id,
          });
          const items = await brReward.buildTeamPayoutItems(tournament, teamRows);
          await winnerPayoutService.ensurePayoutRecords(items);
        } else {
          const brRows = await BattleRoyaleResult.find({ tournamentId: tournament._id });
          await winnerPayoutService.ensurePayoutRecords(
            brReward.buildSoloPayoutItems(tournament, brRows)
          );
        }
      } else {
        const custom = await CustomMatchResult.findOne({ tournamentId: tournament._id });
        if (custom && Number(custom.winnerPrize) > 0) {
          const winnerTeam = await Team.findById(custom.winnerTeamId);
          if (winnerTeam?.captainUserId) {
            await winnerPayoutService.ensurePayoutRecords([
              {
                tournamentId: tournament._id,
                userId: winnerTeam.captainUserId,
                resultId: custom._id,
                resultModel: 'CustomMatchResult',
                amount: Number(custom.winnerPrize) || 0,
                usernameSnapshot: '',
                description: `Clash Squad winner prize — ${tournament.name}`,
              },
            ]);
          }
        }
      }
      payoutSummary = await winnerPayoutService.autoCreditPendingForTournament(tournament._id, {
        tournamentName: tournament.name,
      });

      // Keep legacy prizeCredited flag in sync for custom matches
      if (!lifecycle.isBattleRoyale(tournament)) {
        const paid = await WinnerPayout.countDocuments({
          tournamentId: tournament._id,
          resultModel: 'CustomMatchResult',
          status: 'PAID',
        });
        if (paid > 0) {
          await CustomMatchResult.updateOne(
            { tournamentId: tournament._id },
            { $set: { prizeCredited: true } }
          );
        }
      }
    } catch (payoutErr) {
      console.error('publish-results payout:', payoutErr);
    }

    try {
      const paidPayouts = await WinnerPayout.find({
        tournamentId: tournament._id,
        status: { $in: ['PAID', 'PENDING'] },
        amount: { $gt: 0 },
      }).select('userId amount status');
      const winnerAmounts = {};
      const winnerUserIds = [];
      paidPayouts.forEach((p) => {
        winnerUserIds.push(String(p.userId));
        winnerAmounts[String(p.userId)] = Number(p.amount) || 0;
      });
      await notifyResultsPublished(tournament, { winnerUserIds, winnerAmounts });
    } catch (notifyErr) {
      console.error('results published notify:', notifyErr.message);
    }

    res.json({
      message: 'Results published',
      tournament,
      status: 'completed',
      resultsPublished: true,
      payoutsCredited: payoutSummary.credited || 0,
      autoPaymentEnabled: tournament.autoPaymentEnabled !== false,
      controlWindow: winnerPayoutService.getControlWindow(tournament),
    });
  } catch (e) {
    res.status(500).json({ error: 'Failed to publish results' });
  }
});

