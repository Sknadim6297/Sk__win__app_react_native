const MAX_BONUS_ENTRY_PERCENT = 0.2;

const getEntryPaymentSplit = (user, entryFee) => {
  const fee = Number(entryFee) || 0;
  const bonusBalance = Number(user?.wallet?.bonusBalance) || 0;
  const maxBonusAllowed = Math.floor(fee * MAX_BONUS_ENTRY_PERCENT);
  const bonusUsed = Math.min(bonusBalance, maxBonusAllowed);
  const realMoneyRequired = Math.max(fee - bonusUsed, 0);
  return { bonusUsed, realMoneyRequired, maxBonusAllowed };
};

async function requireAdmin(req, res) {
  const admin = await User.findById(req.userId);
  if (!admin) {
    res.status(401).json({ error: 'Session expired. Please sign in again.' });
    return null;
  }
  if (admin.role !== 'admin') {
    res.status(403).json({ error: 'Admin access required' });
    return null;
  }
  return admin;
}

function formatListItem(tournament, joinStats) {
  const status = lifecycle.getEffectiveStatus(tournament);
  const type = lifecycle.getTournamentType(tournament);
  const structure = lifecycle.getMatchStructure(tournament);
  const charge = lifecycle.resolveEntryCharge(tournament);
  const { joinedCount, capacity, unit, isFull, usesTeams } = joinStats;
  const prizePool = Math.max(0, Number(tournament.prizePool) || 0);
  const perKillRaw = Math.max(0, Number(tournament.perKill) || 0);
  const showPerKill = Boolean(structure.hasKillRewards) && perKillRaw > 0;
  return {
    _id: tournament._id,
    name: tournament.name,
    tournamentType: type,
    category: tournament.category,
    matchKind: structure.kind,
    matchType: structure.matchTypeName || structure.matchType,
    matchTypeName: structure.matchTypeName || structure.matchType,
    formatLabel: structure.formatLabel,
    playerFormatLabel: structure.playerFormatLabel,
    mode: structure.mode,
    modeLabel: structure.modeLabel,
    hasKillRewards: structure.hasKillRewards,
    entryFee: charge.feePerPlayer,
    entryFeePerPlayer: charge.feePerPlayer,
    feePerPlayer: charge.feePerPlayer,
    playersCharged: charge.playersCharged,
    totalAmount: charge.totalAmount,
    perKill: showPerKill ? perKillRaw : 0,
    showPrizePerKill: showPerKill,
    showPrizePool: prizePool > 0,
    joinedCount,
    capacity,
    joinUnit: unit,
    usesTeams,
    isFull,
    showFullBadge: lifecycle.shouldShowFullBadge(status, isFull),
    fullLabel: type === 'custom_match' ? 'Match Full' : 'Tournament Full',
    status,
    lifecycleStatus: status,
    matchDate: tournament.startDate,
    startDate: tournament.startDate,
    gameMode: tournament.gameMode,
    gameName: tournament.game?.name || null,
    maxParticipants: tournament.maxParticipants,
    maxTeams: tournament.maxTeams,
    prizePool,
    map: tournament.map || '',
    mapName: tournament.map || '',
    bannerImage: tournament.bannerImage || '',
    locked: Boolean(tournament.locked),
    resultsPublished: lifecycle.areResultsPublished(tournament),
    isAutoGenerated: Boolean(tournament.isAutoGenerated),
    autoMatchId: tournament.autoMatchId?._id || tournament.autoMatchId || null,
    autoMatchName: tournament.autoMatchId?.name || '',
    autoMatchDisplayId: tournament.autoMatchId?.displayId || '',
    autoMatchNumber: tournament.autoMatchId?.autoMatchNumber || null,
    generatedDate: tournament.generatedDate || '',
  };
}

function escapeRegex(value) {
  return String(value || '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function listStatusMatch(status) {
  const s = String(status || '').trim();
  if (!s) return null;
  if (s === 'upcoming') return { $in: ['upcoming', 'incoming'] };
  if (s === 'live' || s === 'ongoing') return { $in: ['ongoing', 'live'] };
  if (s === 'completed') return { $in: ['completed', 'result_published'] };
  return s;
}

