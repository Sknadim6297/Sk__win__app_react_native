// Register team — Team Name + Side (custom) + Game ID + UID for every player
router.post('/:id/register-team', authMiddleware, async (req, res) => {
  try {
    const user = await User.findById(req.userId);
    if (!user) return res.status(404).json({ error: 'User not found' });
    if (user.role === 'admin') {
      return res.status(403).json({ error: 'Admins cannot join as participants' });
    }
    if (user.status !== 'active') {
      return res.status(403).json({ error: 'Account is not active' });
    }

    const tournament = await Tournament.findById(req.params.id).populate('matchType');
    if (!tournament) return res.status(404).json({ error: 'Tournament not found' });

    if (!lifecycle.isCustomMatch(tournament) && !lifecycle.usesTeamRegistration(tournament)) {
      return res.status(400).json({
        error: 'Team registration is for Clash Squad or Duo/Squad Battle Royale only. Solo uses slot booking.',
      });
    }

    const status = lifecycle.getEffectiveStatus(tournament);
    if (!lifecycle.canJoin(status)) {
      return res.status(400).json({ error: 'Registration is not open' });
    }

    const isCustom = lifecycle.isCustomMatch(tournament);
    const structure = lifecycle.getMatchStructure(tournament);
    const { teamName, teamSide, players, slotNumber: slotNumberRaw } = req.body;
    const sideRaw = String(teamSide || req.body.side || '')
      .trim()
      .toUpperCase()
      .replace('TEAM ', '');
    const side = sideRaw === 'A' || sideRaw === 'B' ? sideRaw : null;

    if (!teamName || !String(teamName).trim()) {
      return res.status(400).json({ error: 'Team name is required' });
    }
    if (isCustom && !side) {
      return res.status(400).json({ error: 'Team side must be Team A or Team B' });
    }

    const requiredPlayers = lifecycle.getPlayersPerTeam(tournament.mode);
    if (!Array.isArray(players) || players.length !== requiredPlayers) {
      const modeLabel = String(tournament.mode || 'solo').toLowerCase();
      return res.status(400).json({
        error:
          modeLabel === 'squad'
            ? 'Squad requires exactly 4 players (Game ID + UID each)'
            : modeLabel === 'duo'
              ? 'Duo requires exactly 2 players (Game ID + UID each)'
              : 'Solo requires exactly 1 player (Game ID + UID)',
        requiredPlayers,
      });
    }

    const normalizedPlayers = players.map((p, idx) => {
      const name = String(typeof p === 'string' ? p : p?.name || p?.gamingUsername || '').trim();
      const gamingUID = String(
        typeof p === 'object' ? p?.gamingUID || p?.uid || p?.gameUID || '' : ''
      ).trim();
      return { name, gamingUID, index: idx };
    });

    const missingName = normalizedPlayers.find((p) => !p.name || p.name.length < 3);
    if (missingName) {
      return res.status(400).json({
        error: `Player ${missingName.index + 1}: Game ID (in-game name) is required (min 3 characters)`,
      });
    }
    const missingUid = normalizedPlayers.find((p) => !p.gamingUID || p.gamingUID.length < 3);
    if (missingUid) {
      return res.status(400).json({
        error: `Player ${missingUid.index + 1}: Game UID is required (min 3 characters)`,
      });
    }

    const teamCount = await Team.countDocuments({ tournamentId: tournament._id, status: 'registered' });
    const maxTeams = isCustom
      ? tournament.maxTeams || 2
      : tournament.maxTeams ||
        Math.floor((tournament.maxParticipants || 50) / requiredPlayers);
    if (teamCount >= maxTeams) {
      return res.status(400).json({
        error: isCustom ? 'Match is full — both teams registered' : 'All team slots are full',
        isFull: true,
      });
    }

    if (isCustom && side) {
      const sideTaken = await Team.findOne({
        tournamentId: tournament._id,
        side,
        status: 'registered',
      });
      if (sideTaken) {
        return res.status(400).json({ error: `Team ${side} is already registered` });
      }
    }

    let slotNumber = null;
    if (!isCustom && structure.usesTeamRegistration) {
      slotNumber = Number(slotNumberRaw);
      if (!slotNumber || slotNumber < 1 || slotNumber > structure.totalSlots) {
        const taken = await Team.find({ tournamentId: tournament._id, status: 'registered' }).select('slotNumber');
        const used = new Set(taken.map((t) => Number(t.slotNumber)).filter(Boolean));
        for (let i = 1; i <= structure.totalSlots; i += 1) {
          if (!used.has(i)) {
            slotNumber = i;
            break;
          }
        }
      }
      if (!slotNumber) {
        return res.status(400).json({ error: 'All slots are full' });
      }
      const slotTaken = await Team.findOne({
        tournamentId: tournament._id,
        slotNumber,
        status: 'registered',
      });
      if (slotTaken) {
        return res.status(400).json({ error: `Slot ${slotNumber} is already booked` });
      }
    }

    const nameTaken = await Team.findOne({
      tournamentId: tournament._id,
      status: 'registered',
      name: { $regex: `^${String(teamName).trim().replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`, $options: 'i' },
    });
    if (nameTaken) {
      return res.status(400).json({ error: 'A team with this name is already registered in this match' });
    }

    const existingMember = await TeamMember.findOne({
      tournamentId: tournament._id,
      userId: req.userId,
    });
    const existingParticipant = await TournamentParticipant.findOne({
      tournamentId: tournament._id,
      userId: req.userId,
    });
    if (existingMember || existingParticipant) {
      return res.status(400).json({ error: 'You are already registered in this tournament' });
    }

    // Entry fee is per player; captain pays fee × roster size for duo/squad/clash
    const charge = lifecycle.resolveEntryCharge(tournament);
    const { bonusUsed, realMoneyRequired } = getEntryPaymentSplit(user, charge.totalAmount);
    if (user.wallet.balance < realMoneyRequired) {
      return res.status(400).json({
        error: `Insufficient real balance! Team entry is ₹${charge.totalAmount} (₹${charge.feePerPlayer} × ${charge.playersCharged} players; need ₹${realMoneyRequired} real; can use ₹${bonusUsed} bonus). Current: ₹${user.wallet.balance}.`,
      });
    }

    const teamPayload = {
      tournamentId: tournament._id,
      name: String(teamName).trim(),
      players: normalizedPlayers.map(({ name, gamingUID }) => ({ name, gamingUID })),
      captainUserId: req.userId,
    };
    if (isCustom && side) teamPayload.side = side;
    if (slotNumber) teamPayload.slotNumber = slotNumber;

    const team = await Team.create(teamPayload);

    await TeamMember.create({
      tournamentId: tournament._id,
      teamId: team._id,
      userId: req.userId,
      gamingUsername: normalizedPlayers[0].name,
      gamingUID: normalizedPlayers[0].gamingUID,
      role: 'captain',
    });

    user.wallet.balance -= realMoneyRequired;
    user.wallet.bonusBalance = Math.max((user.wallet.bonusBalance || 0) - bonusUsed, 0);
    user.wallet.bonusUsed = (user.wallet.bonusUsed || 0) + bonusUsed;
    user.tournament.participatedCount = (user.tournament.participatedCount || 0) + 1;
    await user.save();

    const entryLabel = isCustom ? 'Clash Squad' : 'Battle Royale';
    const sideLabel = side ? ` / Team ${side}` : '';

    await WalletTransaction.create({
      userId: req.userId,
      type: 'tournament_entry',
      amount: charge.totalAmount,
      tournamentId: tournament._id,
      description: `${entryLabel} team entry (₹${charge.feePerPlayer}/player × ${charge.playersCharged} = ₹${charge.totalAmount}) — ${tournament.name}${sideLabel}`,
      status: 'completed',
    });

    await notifyTournamentJoined(req.userId, tournament).catch(() => {});

    tournament.currentParticipants = (teamCount + 1) * requiredPlayers;
    if (!tournament.registeredPlayers.some((id) => String(id) === String(req.userId))) {
      tournament.registeredPlayers.push(req.userId);
    }
    await tournament.save();

    res.status(201).json({
      message:
        charge.playersCharged > 1
          ? `Team registered. Charged ₹${charge.totalAmount} (₹${charge.feePerPlayer} × ${charge.playersCharged} players).`
          : 'Team registered successfully.',
      team: {
        _id: team._id,
        name: team.name,
        side: team.side,
        players: team.players,
      },
      payment: {
        entryFee: charge.feePerPlayer,
        feePerPlayer: charge.feePerPlayer,
        playersCharged: charge.playersCharged,
        totalAmount: charge.totalAmount,
        chargedPer: charge.chargedPer,
        bonusUsed,
        realMoneyRequired,
      },
    });
  } catch (e) {
    console.error('register-team:', e);
    if (e.code === 11000) {
      return res.status(400).json({ error: 'Team name or side is already taken for this match' });
    }
    res.status(500).json({ error: e.message || 'Failed to register team' });
  }
});

